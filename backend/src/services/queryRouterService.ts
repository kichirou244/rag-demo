  public static classify(query: string): QueryIntent {
    const normalized = query.toLowerCase().trim();

    const hasTraffic = this.TRAFFIC_KEYWORDS.some((kw) =>
      normalized.includes(kw)
    );
    if (hasTraffic) {
      return "TRAFFIC_LAW";
    }

    const hasGreeting = this.GREETING_KEYWORDS.some((kw) =>
      normalized.includes(kw)
    );
    if (hasGreeting) {
      return "GREETING";
    }

    return "OUT_OF_SCOPE";
  }
